#Requires -Version 7.0
<# Synthetic archives are generated only from our own text; never execute a reference. #>
param([Parameter(Mandatory = $true)] [string] $OutputDirectory)
$ErrorActionPreference = 'Stop'
Set-StrictMode -Version Latest
. (Join-Path $PSScriptRoot 'prepare-signed-test-fixture.ps1')
[void][IO.Directory]::CreateDirectory($OutputDirectory)
$root = [IO.Path]::GetFullPath($OutputDirectory)
$program = [Text.Encoding]::UTF8.GetBytes('our non-executable reference data')
$notice = [Text.Encoding]::UTF8.GetBytes('Our generated fixture notice, MIT OR Apache-2.0.')
function Digest([byte[]] $Bytes) {
  $hash = [Security.Cryptography.SHA256]::Create()
  try { [BitConverter]::ToString($hash.ComputeHash($Bytes)).Replace('-', '').ToLowerInvariant() }
  finally { $hash.Dispose() }
}
function Refuse([scriptblock] $Action, [string] $Case, [string] $ExpectedMessage) {
  $failed = $false; $message = ''
  try { & $Action } catch { $failed = $true; $message = $_.Exception.Message }
  if (-not $failed) { throw "Expected refusal: $Case" }
  if ($ExpectedMessage -and -not $message.Contains($ExpectedMessage)) { throw "Wrong refusal for ${Case}: $message" }
  Write-Output "PASS refusal: $Case"
}
function Archive([string] $Name, [string[]] $Entries) {
  $path = Join-Path $root "$Name.zip"
  $stream = [IO.File]::Open($path, [IO.FileMode]::CreateNew)
  $zip = [IO.Compression.ZipArchive]::new($stream, [IO.Compression.ZipArchiveMode]::Create)
  try {
    foreach ($name in $Entries) {
      $entry = $zip.CreateEntry($name)
      $output = $entry.Open()
      $data = if ($name -ieq 'pwsh.exe') { $program } else { $notice }
      try { $output.Write($data, 0, $data.Length) } finally { $output.Dispose() }
    }
  } finally { $zip.Dispose(); $stream.Dispose() }
  return $path
}
function Pin([string] $Archive) {
  [pscustomobject]@{
    source = [pscustomobject]@{size = [IO.FileInfo]::new($Archive).Length; sha256 = (Get-FileHash -LiteralPath $Archive -Algorithm SHA256).Hash.ToLowerInvariant()}
    artifact = [pscustomobject]@{entry = 'pwsh.exe'; size = $program.Length; sha256 = (Digest $program)}
    notices = @('LICENSE.txt', 'ThirdPartyNotices.txt')
  }
}
function Destination([string] $Name) {
  $path = Join-Path $root $Name
  [void][IO.Directory]::CreateDirectory($path)
  [IO.File]::WriteAllText((Join-Path $path 'personal.txt'), 'existing data')
  return $path
}
$archive = Archive 'good' @('pwsh.exe','LICENSE.txt','ThirdPartyNotices.txt','../unselected-data.txt')
$pin = Pin $archive
$out = Destination 'verified'
Expand-PinnedReference $archive $pin $out
if ((Get-FileHash -LiteralPath (Join-Path $out 'pwsh.exe') -Algorithm SHA256).Hash.ToLowerInvariant() -cne $pin.artifact.sha256) { throw 'Wrong extracted bytes.' }
foreach ($name in $pin.notices) { if ([IO.File]::ReadAllText((Join-Path $out $name)) -cne [Text.Encoding]::UTF8.GetString($notice)) { throw 'Notice was not retained exactly.' } }
if ((Get-ChildItem -LiteralPath $out).Count -ne 4 -or (Test-Path (Join-Path $root 'unselected-data.txt'))) { throw 'Unexpected archive content escaped the explicit selection.' }
Write-Output 'PASS exact pinned reference and upstream notices, no broad extraction.'

foreach ($case in @('archive-hash','archive-length','entry-hash','entry-length')) {
  $bad = Pin $archive
  switch ($case) {
    'archive-hash' { $bad.source.sha256 = '0' * 64 }
    'archive-length' { $bad.source.size++ }
    'entry-hash' { $bad.artifact.sha256 = '0' * 64 }
    'entry-length' { $bad.artifact.size++ }
  }
  $out = Destination $case
  Refuse { Expand-PinnedReference $archive $bad $out } $case
  if ([IO.File]::ReadAllText((Join-Path $out 'personal.txt')) -cne 'existing data') { throw 'A refusal modified unrelated data.' }
}
foreach ($case in @('duplicate','case-duplicate','wrong-case','nested-only','missing-notice')) {
  $entries = switch ($case) {
    'duplicate' { @('pwsh.exe','pwsh.exe','LICENSE.txt','ThirdPartyNotices.txt') }
    'case-duplicate' { @('pwsh.exe','PWSH.EXE','LICENSE.txt','ThirdPartyNotices.txt') }
    'wrong-case' { @('PWSH.EXE','LICENSE.txt','ThirdPartyNotices.txt') }
    'nested-only' { @('nested/pwsh.exe','LICENSE.txt','ThirdPartyNotices.txt') }
    'missing-notice' { @('pwsh.exe','LICENSE.txt') }
  }
  $file = Archive $case $entries; $bad = Pin $file; $out = Destination $case
  Refuse { Expand-PinnedReference $file $bad $out } $case
}
$caseNumber = 0
foreach ($name in @('nested/pwsh.exe', 'nested\pwsh.exe', 'C:pwsh.exe', '.', '..')) {
  $caseNumber++; $case = "unsafe-root-$caseNumber"
  $file = Archive $case @($name,'LICENSE.txt','ThirdPartyNotices.txt')
  $bad = Pin $file; $bad.artifact.entry = $name
  # Match these generated bytes, so a missing name guard cannot pass via size/hash refusal.
  $bad.artifact.size = $notice.Length; $bad.artifact.sha256 = Digest $notice
  $out = Destination $case
  Refuse { Expand-PinnedReference $file $bad $out } $case 'Fixture outputs must be explicit root filenames.'
}
$aborted = Join-Path $root 'injected-transfer-failure'
$savedReceiver = ${function:Receive-PinnedArchive}
try {
  Set-Item -Path Function:Receive-PinnedArchive -Value { throw 'Our injected transfer failure.' }
  Refuse { New-PinnedSignedFixture $aborted } 'transfer failure does not publish a fixture' 'Our injected transfer failure.'
} finally { Set-Item -Path Function:Receive-PinnedArchive -Value $savedReceiver }
if ((Test-Path -LiteralPath $aborted) -or @(Get-ChildItem -LiteralPath $root -Filter 'injected-transfer-failure.partial-*').Count -ne 0) { throw 'Failed setup left its final or owned staging directory.' }
$corrupt = Join-Path $root 'not-a-zip'; [IO.File]::WriteAllText($corrupt, 'original malformed ZIP fixture')
$out = Destination 'corrupt'; $bad = Pin $corrupt
Refuse { Expand-PinnedReference $corrupt $bad $out } 'malformed archive even with matching outer hash'

foreach ($case in @('exact','short','long','hash')) {
  $data = switch ($case) { 'short' { $program[0..($program.Length-2)] } 'long' { $program + [byte]1 } default { $program } }
  $stream = [IO.MemoryStream]::new([byte[]]$data)
  try {
    $file = Join-Path $root "stream-$case"
    $digest = if ($case -eq 'hash') { '0' * 64 } else { Digest $program }
    if ($case -eq 'exact') { Copy-PinnedStream $stream $file $program.Length $digest }
    else { Refuse { Copy-PinnedStream $stream $file $program.Length $digest } "bounded stream $case" }
    if ($stream.Position -gt $program.Length + 1) { throw 'Unbounded read past the expected stream.' }
  } finally { $stream.Dispose() }
}
$out = Destination 'existing-destination'
Refuse { New-PinnedSignedFixture $out } 'existing final directory never overwritten'
if ([IO.File]::ReadAllText((Join-Path $out 'personal.txt')) -cne 'existing data') { throw 'Existing destination changed.' }
Write-Output 'PASS all data-only provisioning regressions; no signing or native runtime acceptance claimed.'
